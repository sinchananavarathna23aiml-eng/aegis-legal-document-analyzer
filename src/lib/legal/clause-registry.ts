export function getRelevantClauses(contractType: ContractType): ClauseRegistryEntry[] {
  return CLAUSE_REGISTRY.filter((c) => c.relevantContractTypes.includes(contractType) || c.relevantContractTypes.includes("general"));
}

export function getClauseById(id: string): ClauseRegistryEntry | undefined {
  return CLAUSE_REGISTRY.find((c) => c.id === id);
}

export function getClausesByImportance(importance: ClauseRegistryEntry["importance"]): ClauseRegistryEntry[] {
  return CLAUSE_REGISTRY.filter((c) => c.importance === importance);
}

